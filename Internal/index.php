Cricket Team Performance Evaluation System with Predictive Analytics


The quantization of player form in cricket from the previous season is a pivotal aspect of this
project, involving the systematic assessment and categorization of player performance through
statistical metrics and criteria. Utilizing a quantization methodology, cricket analysts and team
management can objectively evaluate and compare player performances, providing a
standardized measure expressed through grades such as A, B, C, and more. This simplified
representation distills nuanced aspects of a player's contributions over the preceding cricket
season into concise summaries, facilitating effective communication among team members,
coaches, and fans. Additionally, it aids decision-making processes, team selection, and strategic
planning for the upcoming season.
The system will be developed using PHP for the frontend, MySQL for the backend, and Python
for predictive analysis through Google Colab.
This project presents a web-based system for evaluating and predicting cricket player
performance, divided into three modules: Admin, Player, and Club Management.


Admin Module:
Login/Logout: Enables authorized admins to access and manage the system.
Player Approval: Review and approve/reject player registrations based on eligibility criteria.
Legal Document Management: Upload and manage legal documents related to players and
contracts.
Team Selection Approval: Provide final approval for team selections submitted by clubs.

Player Module:
Login/Logout: Secure access for registered players to their profiles.
Match Statistics: Add and update individual match performance data (runs, wickets, etc.).
Strengths & Preferences: Indicate personal strengths and preferred playing positions.
Contract Distribution: Set desired salary expectations for contract negotiations.
Club Management: Join and manage affiliations with cricket clubs.
Performance Statistics: View personal performance data and analysis in various formats.


Club Management Module:
Registration/Login/Logout: Register and manage club profiles.
Player Management: View profiles of registered players, filter based on preferences.
Contract Details: Offer and manage contracts to players, including salary negotiations.
Player List Management: Maintain a roster of contracted players.
Performance Prediction: Utilize the system's prediction engine to forecast player performance.


Technical Implementation:
Frontend: PHP for a user-friendly web interface.
Backend: MySQL database to store player, team, and performance data.
Predictive Analysis: Python in Google Colab for advanced performance prediction modeling.


